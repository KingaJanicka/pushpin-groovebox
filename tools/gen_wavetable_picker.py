"""Write the wavetable picker into the Wavetable and Window oscillator devices.

    python tools/gen_wavetable_picker.py [surge-wavetables-folder]

The picker is a switch with a group per factory category (Basic, Generated,
...), each holding a menu of that category's wavetables, the way the Filters
device nests filter types. Items name their wavetable ("Basic/Sine") rather
than giving Surge's id: ids depend on the machine (see wavetables.py), so
pushpin looks them up when it loads the device. "value": -1 is a placeholder
that Surge would ignore (out-of-range ids are).

Rewrites the switch in place (the switch whose items pick wavetables), or
puts it in place of the /wavetable/... spacers on the device's second page.
"""
from __future__ import annotations

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

import wavetables  # noqa: E402

DEVICES = {
    "definitions/device_definitions/wavetable_1.json": 1,
    "definitions/device_definitions/wavetable_2.json": 2,
    "definitions/device_definitions/window_1.json": 1,
    "definitions/device_definitions/window_2.json": 2,
}


def picker(names: list[str], osc: int) -> dict:
    categories: dict[str, list[str]] = {}
    for name in names:
        category, _, table = name.rpartition("/")
        categories.setdefault(category, []).append(table)
    groups = []
    for category in sorted(categories, key=str.lower):
        items = [
            {
                "$type": "menu-item",
                "label": table,
                "wavetable": f"{category}/{table}",
                "onselect": {
                    "$type": "message",
                    "$comment": "id looked up from 'wavetable'",
                    "address": f"/wavetable/a/osc/{osc}/id",
                    "value": -1,
                },
            }
            for table in sorted(categories[category], key=str.lower)
        ]
        groups.append({
            "$type": "group",
            "label": category,
            # (the spacer keeps the controls after the picker where they were)
            "controls": [{"$type": "control-menu", "items": items}, {"$type": "control-spacer"}],
        })
    return {
        "$type": "control-switch",
        "$comment": "Wavetable: category, then table. Generated by tools/gen_wavetable_picker.py",
        "clicks_per_group": 25,
        "select_by_value": True,
        "groups": groups,
    }


def is_picker(control: dict) -> bool:
    return control["$type"] == "control-switch" and any(
        "wavetable" in item or item.get("onselect", {}).get("address", "").startswith("/wavetable/")
        for group in control["groups"]
        for c in group["controls"]
        for item in c.get("items", [])
    )


def is_placeholder(control: dict) -> bool:
    return control["$type"] == "control-spacer-address" and control["address"].startswith("/wavetable/")


def insert(controls: list[dict], switch: dict) -> list[dict]:
    for i, control in enumerate(controls):
        if is_picker(control):
            return controls[:i] + [switch] + controls[i + 1:]
    start = next(i for i, c in enumerate(controls) if is_placeholder(c))
    end = start
    while end < len(controls) and is_placeholder(controls[end]):
        end += 1
    return controls[:start] + [switch] + controls[end:]


def main() -> None:
    folder = sys.argv[1] if len(sys.argv) > 1 else next(f for f in wavetables.FACTORY_FOLDERS if os.path.isdir(f))
    names = wavetables.scan_wavetables(folder)
    for path, osc in DEVICES.items():
        full = os.path.join(ROOT, path)
        with open(full) as f:
            device = json.load(f)
        device["controls"] = insert(device["controls"], picker(names, osc))
        with open(full, "w") as f:
            json.dump(device, f, indent="\t", ensure_ascii=False)
            f.write("\n")
        print(f"{path}: {len(names)} wavetables")


if __name__ == "__main__":
    main()
