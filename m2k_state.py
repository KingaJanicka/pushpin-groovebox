"""Whole mono2k sounds: saving and loading what a track's mono2k voice plays.

A sound is a machine and every one of MONO2K's track parameters (71). pushpin
never reads anything back from m2k-jack, but it doesn't need to: the voice's
MidiCCClient keeps the last value it sent for every address, and a machine's
init (engines/m2k/definitions) sends all its parameters, so the client's cache
*is* the track's sound. ``capture`` reads it from there; ``apply`` sends a
sound back through the same client (the machine first, which loads its INIT
in m2k-jack, then every parameter), so the device pages follow.

Parameters a page control reaches go as ``/cc/<cc>`` (the pages listen there),
the others as ``/m2k/param/<n>`` (NRPN 1:<n>). Which is which, each machine's
INIT sound and MONO2K's factory library come from engines/m2k/sounds.json,
generated by engines/m2k/gen_definitions.py.

Files (JSON): {"format": 1, "engine": "mono2k", "name", "machine",
"machine_name", "params": [71 numbers]}.
"""
from __future__ import annotations

import json
import logging
import os
import re
from dataclasses import dataclass, field
from glob import glob
from pathlib import Path
from typing import Any

logger = logging.getLogger("m2k_state")

SOUNDS_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "engines", "m2k", "sounds.json")
MACHINE_ADDRESS = "/cc/14"
# LEVL, the track's output level. MONO2K's gain for it is square-law
# (T_VOL[n] ~ (n / 127)^2), so a gain g scales the CC value by sqrt(g).
LEVEL_ADDRESS = "/cc/7"
FORMAT = 1
LFO_TRACKS = 8                             # TRCK: 0 the LFO's own track, 1-8 track 1-8

# The preset browser's top level for a mono2k track; a sound's id is its path
# in the tree ("Factory/KICK/BOOM808", "Machines/GND-SIN", "User/my bass").
FACTORY = "Factory"
MACHINES = "Machines"
USER = "User"


@dataclass
class Sound:
    machine: int
    params: list[float]
    name: str = ""

    def to_json(self, catalogue: "M2KSounds | None" = None) -> dict[str, Any]:
        data: dict[str, Any] = {"format": FORMAT, "engine": "mono2k", "name": self.name, "machine": self.machine}
        if catalogue is not None and 0 <= self.machine < len(catalogue.machines):
            data["machine_name"] = catalogue.machines[self.machine]["name"]
        data["params"] = [round(float(v), 4) for v in self.params]
        return data


@dataclass
class M2KSounds:
    """sounds.json: the parameter map, the machines' INIT sounds and the library."""

    param_count: int
    cc_of: dict[int, int]                     # parameter number -> its CC (page controls only)
    machines: list[dict[str, Any]]            # {"index", "name", "kit"}
    categories: list[str]
    library: list[dict[str, Any]]             # {"name", "category", "machine", "root", "what", "kit"}
    user_folder: str | None = None
    labels: list[str] = field(default_factory=list)

    @classmethod
    def load(cls, path: str = SOUNDS_PATH, user_folder: str | None = None) -> "M2KSounds | None":
        try:
            with open(path) as f:
                data = json.load(f)
        except (OSError, ValueError) as e:
            logger.warning("no mono2k sounds (%s): %s", path, e)
            return None
        params = sorted(data["params"], key=lambda p: p["param"])
        return cls(
            param_count=int(data["param_count"]),
            cc_of={p["param"]: p["cc"] for p in params if p.get("cc") is not None},
            machines=data["machines"],
            categories=data["categories"],
            library=data["library"],
            user_folder=user_folder,
            labels=[p["label"] for p in params],
        )

    # --------------------------------------------------------------- addresses

    def address(self, param: int) -> str:
        cc = self.cc_of.get(param)
        return f"/cc/{cc}" if cc is not None else f"/m2k/param/{param}"

    # ------------------------------------------------------------------ sounds

    def machine_sound(self, machine: int) -> Sound:
        m = self.machines[machine]
        return Sound(machine, [float(v) for v in m["kit"]], m["name"])

    def _complete(self, machine: int, params: list[Any]) -> list[float]:
        """A saved sound's parameters, missing ones from its machine's INIT."""
        full = [float(v) for v in self.machines[machine]["kit"]]
        for i, v in enumerate(params[: self.param_count]):
            try:
                full[i] = float(v)
            except (TypeError, ValueError):
                pass
        for i in self.lfo_track_params:
            # Before TRCK had a page, files kept MONO2K's own raw value (the
            # INIT's 10, track 1, for every track); pushpin's TRCK is 0 (the
            # LFO's own track) or 1-8, so anything else means the old default.
            if i < len(full) and not 0 <= full[i] <= LFO_TRACKS:
                full[i] = 0.0
        return full

    @property
    def lfo_track_params(self) -> list[int]:
        return [i for i, label in enumerate(self.labels) if label == "TRCK"]

    def sound_from_json(self, data: Any) -> Sound | None:
        try:
            machine = int(data["machine"])
            if not 0 <= machine < len(self.machines):
                return None
            return Sound(machine, self._complete(machine, list(data.get("params", []))), str(data.get("name", "")))
        except (TypeError, KeyError, ValueError):
            return None

    def read(self, path: str) -> Sound | None:
        try:
            with open(path) as f:
                return self.sound_from_json(json.load(f))
        except (OSError, ValueError):
            return None

    def write(self, path: str, sound: Sound) -> None:
        os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
        tmp = f"{path}.tmp"
        with open(tmp, "w") as f:
            json.dump(sound.to_json(self), f, indent=1)
        os.replace(tmp, path)               # (a power cut mid-save leaves the old file)

    # -------------------------------------------------------- the browser tree

    def user_files(self) -> dict[str, str]:
        if not self.user_folder or not os.path.isdir(self.user_folder):
            return {}
        return {Path(p).stem: p for p in sorted(glob(os.path.join(self.user_folder, "*.json")))}

    def tree(self) -> dict[str, Any]:
        """The preset browser's tree: leaves are sound ids."""
        factory: dict[str, Any] = {}
        for cat in self.categories:
            sounds = {s["name"]: f"{FACTORY}/{cat}/{s['name']}" for s in self.library if s["category"] == cat}
            if sounds:
                factory[cat] = sounds
        tree: dict[str, Any] = {
            FACTORY: factory,
            MACHINES: {m["name"]: f"{MACHINES}/{m['name']}" for m in self.machines},
        }
        user = {stem: f"{USER}/{stem}" for stem in self.user_files()}
        if user:
            tree[USER] = user
        return tree

    def resolve(self, sound_id: str | None) -> Sound | None:
        """The sound a browser id names, or None."""
        if not sound_id:
            return None
        parts = sound_id.split("/")
        if parts[0] == FACTORY and len(parts) == 3:
            for s in self.library:
                if s["category"] == parts[1] and s["name"] == parts[2]:
                    return Sound(int(s["machine"]), [float(v) for v in s["kit"]], s["name"])
        elif parts[0] == MACHINES and len(parts) == 2:
            for m in self.machines:
                if m["name"] == parts[1]:
                    return self.machine_sound(int(m["index"]))
        elif parts[0] == USER and len(parts) == 2:
            path = self.user_files().get(parts[1])
            if path:
                sound = self.read(path)
                if sound is not None:
                    sound.name = parts[1]
                return sound
        return None

    def save_user(self, sound: Sound) -> str:
        """Save ``sound`` as a new user preset; returns its id. Named after its
        machine and a number: "<MACHINE> 1", "<MACHINE> 2", ..."""
        assert self.user_folder
        base = re.sub(r"[^A-Za-z0-9+ -]", "", self.machines[sound.machine]["name"]) or "SOUND"
        existing = set(self.user_files())
        n = 1
        while f"{base} {n}" in existing:
            n += 1
        stem = f"{base} {n}"
        sound = Sound(sound.machine, list(sound.params), stem)
        self.write(os.path.join(self.user_folder, f"{stem}.json"), sound)
        return f"{USER}/{stem}"


# ---------------------------------------------------------------- the voice


def scaled_level(levl: float, gain: float) -> float:
    """The LEVL that plays a sound whose own LEVL is ``levl`` at ``gain`` x its
    level (``gain`` linear, 0..1)."""
    return min(max(float(levl), 0.0), 127.0) * min(max(gain, 0.0), 1.0) ** 0.5


def capture(client: Any, catalogue: M2KSounds, unlocked: dict[str, float] | None = None) -> Sound | None:
    """The sound a mono2k voice's client last sent, or None before any machine.

    ``unlocked`` (address -> value) wins over what was sent: the values the
    sequencer's p-locks playing now will go back to, so a lock isn't saved."""
    values: dict[str, float] = getattr(client, "values", {})
    if MACHINE_ADDRESS not in values:
        return None
    machine = int(round(values[MACHINE_ADDRESS]))
    if not 0 <= machine < len(catalogue.machines):
        return None
    params = [float(v) for v in catalogue.machines[machine]["kit"]]
    for p in range(catalogue.param_count):
        address = catalogue.address(p)
        if address in values:
            params[p] = float(values[address])
        if unlocked and address in unlocked:
            params[p] = float(unlocked[address])
    return Sound(machine, params, catalogue.machines[machine]["name"])


def apply(sound: Sound, client: Any, catalogue: M2KSounds) -> None:
    """Make the voice play ``sound``: its machine (m2k-jack loads that INIT),
    then every parameter, all through the client so the pages follow."""
    client.send_message(MACHINE_ADDRESS, float(sound.machine))
    for p, value in enumerate(sound.params[: catalogue.param_count]):
        client.send_message(catalogue.address(p), float(value))
